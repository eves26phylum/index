function generateBootLogs(count: number): string[] {
    const logs: string[] = [];
    for (let i = 0; i < count; i++) {
        const ts = nextTimestamp();
        const process = MACOS_PROCESSES[randInt(0, MACOS_PROCESSES.length - 1)];
        const pid = randInt(1, 65535);
        const level = pickLogLevel();
        const message = pick(MESSAGE_GENERATORS)(process, pid) + pick(MESSAGE_GENERATORS)(process, pid) + pick(MESSAGE_GENERATORS)(process, pid) + pick(MESSAGE_GENERATORS)(process, pid);
        logs.push(`${ts} [${level}] ${process}[${pid}]: ${message}`);
    }
    return logs;
}

