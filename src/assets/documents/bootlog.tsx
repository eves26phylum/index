let _bootMs = 0;
function nextTimestamp(): string {
    _bootMs += randInt(2, 55);
    const ms = _bootMs % 1000;
    const sTotal = Math.floor(_bootMs / 1000);
    const sec = sTotal % 60;
    const minTot = Math.floor(sTotal / 60);
    const min = minTot % 60;
    const hr = Math.floor(minTot / 60);
    const today = new Date();
    const dayName = today.getDate();
    const monthName = today.toLocaleString('default', { month: 'long' });

    return `${monthName} ${dayName}  ${String(hr).padStart(2, "0")}: ${String(min).padStart(2, "0")}: ${String(sec).padStart(2, "0")}. ${String(ms).padStart(3, "0")}`;
}

