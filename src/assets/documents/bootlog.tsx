function randHex(length: number): string {
    const chars = '0123456789abcdef';
    let result = '';

    for (let i = 0; i < length; i++) {
        result += chars.charAt(Math.floor(Math.random() * chars.length));
    }

    return result;
}
function rand() {
    return Math.random();
}
function pick<T>(arr: T[]): T {
    return arr[Math.floor(rand() * arr.length)];
}
function randInt(min: number, max: number) {
    return Math.floor(Math.random() * (max - min + 1)) + min;
}
function randVersion(): string {
    return `${randInt(1, 30)}.${randInt(0, 9)}.${randInt(0, 99)}`;
}
function pickLogLevel(): string {
    const n = rand();
    if (n < 0.60) return "Default";
    if (n < 0.85) return "Info   ";
    if (n < 0.95) return "Debug  ";
    if (n < 0.99) return "Error  ";
    return "Fault  ";
}
function randIp(): string {
    return `${randInt(10, 192)}.${randInt(0, 255)}.${randInt(0, 255)}.${randInt(1, 254)}`;
}

